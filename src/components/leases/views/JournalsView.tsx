"use client";
import Link from "next/link";
import { useMemo, useState } from "react";
import { BookOpen, Download } from "lucide-react";
import { D, ACCOUNT_LABELS } from "@/lib/leases/engine";
import { fmtDateTime, glOf, periodLabel, member } from "@/lib/leases/model";
import { batchTotals } from "@/lib/leases/store";
import { PageHeader, Card, Money, StatusBadge, EmptyState, Btn, BtnLink, Tabs, Banner } from "@/components/ll/Kit";
import { DataTable } from "@/components/ll/DataTable";
import { useLeasesState } from "../use-leases";
import { RequireSetup, PersonById } from "../common";
import { downloadBatch } from "./CloseView";
import type { JournalBatch } from "@/lib/leases/types";

const TONE = { draft: "neutral", approved: "info", exported: "info", posted: "success", reversed: "muted" } as const;

export function JournalsView() {
  const st = useLeasesState()!;
  return (
    <RequireSetup>
      <PageHeader title="Journals" sub="One batch per closed period. Posted batches are never edited — they're reversed with a linked batch." />
      <Card pad={false}>
        <DataTable<JournalBatch>
          caption="Journal batches"
          rows={st.batches}
          rowKey={(b) => b.id}
          href={(b) => `/leases/journals/${b.id}`}
          columns={[
            { key: "id", header: "Batch", cell: (b) => <span className="ll-mono">{b.id}</span> },
            { key: "period", header: "Period", cell: (b) => periodLabel(b.period) },
            { key: "type", header: "Type", cell: (b) => (b.type === "reversal" ? <StatusBadge tone="warning" dot={false}>Reversal of {b.reversalOf}</StatusBadge> : "Period") },
            { key: "lines", header: "Lines", num: true, cell: (b) => b.lines.length },
            { key: "total", header: "Total debits", num: true, cell: (b) => <Money value={batchTotals(b).dr} /> },
            { key: "status", header: "Status", cell: (b) => <StatusBadge tone={TONE[b.status]}>{b.status}</StatusBadge> },
            { key: "erp", header: "ERP ref", cell: (b) => <span className="ll-code">{b.erpRef ?? "—"}</span> },
          ]}
          card={(b) => ({ title: <span className="ll-mono">{b.id}</span>, badge: <StatusBadge tone={TONE[b.status]}>{b.status}</StatusBadge>, meta: [periodLabel(b.period), `${b.lines.length} lines`, b.erpRef ?? ""] })}
          empty={<EmptyState icon={BookOpen} title="No journal batches yet" body="Batches are generated during the period close." actions={<BtnLink href="/leases/close" variant="primary">Go to period close</BtnLink>} />}
        />
      </Card>
    </RequireSetup>
  );
}

export function JournalBatchView({ id }: { id: string }) {
  const st = useLeasesState()!;
  const b = st.batches.find((x) => x.id === id);
  const [view, setView] = useState<"account" | "lease">("account");
  const grouped = useMemo(() => {
    if (!b) return [];
    const gl = (glOf(st)?.accounts ?? {}) as Record<string, string>;
    const m = new Map<string, { key: string; label: React.ReactNode; dr: ReturnType<typeof D>; cr: ReturnType<typeof D>; n: number }>();
    for (const l of b.lines) {
      const lease = st.leases.find((x) => x.id === l.leaseId);
      const key = view === "account" ? l.account : l.leaseId;
      const g = m.get(key) ?? { key, label: view === "account" ? <>{gl[l.account] && <span className="ll-code" style={{ marginRight: 6 }}>{gl[l.account]}</span>}{ACCOUNT_LABELS[l.account]}</> : <Link className="ll-link" href={`/leases/${l.leaseId}`}>{lease?.code} · {lease?.name}</Link>, dr: D(0), cr: D(0), n: 0 };
      g.dr = g.dr.plus(l.debit);
      g.cr = g.cr.plus(l.credit);
      g.n += 1;
      m.set(key, g);
    }
    return [...m.values()];
  }, [b, view, st]);
  if (!b) return <div className="ll-card"><EmptyState icon={BookOpen} title="Batch not found" actions={<BtnLink href="/leases/journals">All journals</BtnLink>} /></div>;
  const t = batchTotals(b);
  const catchUp = b.lines.filter((l) => l.catchUp);
  return (
    <>
      <PageHeader
        back={{ href: "/leases/journals", label: "Journals" }}
        title={<span className="ll-mono">{b.id}</span>}
        badge={<StatusBadge tone={TONE[b.status]}>{b.status}</StatusBadge>}
        sub={<>{periodLabel(b.period)} · {b.lines.length} lines · generated by {member(st, b.createdBy).name} {fmtDateTime(b.createdAt)}</>}
        actions={b.status !== "draft" ? <Btn onClick={() => downloadBatch(b.id)}><Download size={14} /> Export</Btn> : undefined}
      />
      {b.status === "reversed" && <Banner tone="locked" title="Reversed">This batch was reversed when the period was reopened. See the reversal batch in the list.</Banner>}
      {b.type === "reversal" && <Banner tone="warning" title={`Reversal of ${b.reversalOf}`}>Every line is the mirror of the original, so the GL nets to zero for the reopened period.</Banner>}
      {catchUp.length > 0 && <Banner tone="info" title={`${catchUp.length} catch-up lines`}>Back-dated changes that affect locked months. They post in this period; the locked months stay unchanged.</Banner>}
      <div className="ll-kpis">
        <div className="ll-kpi"><span className="k">Debits</span><span className="v"><Money value={t.dr} /></span></div>
        <div className="ll-kpi"><span className="k">Credits</span><span className="v"><Money value={t.cr} /></span><span className="s">{t.balanced ? "Balanced ✓" : "Out of balance"}</span></div>
        <div className="ll-kpi"><span className="k">Approved by</span><span className="v" style={{ fontSize: 15 }}><PersonById st={st} id={b.approvedBy} /></span><span className="s">{fmtDateTime(b.approvedAt)}</span></div>
        <div className="ll-kpi"><span className="k">ERP reference</span><span className="v" style={{ fontSize: 15 }}>{b.erpRef ?? "—"}</span><span className="s">{b.postedAt ? `Posted ${fmtDateTime(b.postedAt)}` : "Not posted"}</span></div>
      </div>
      <Tabs label="Group by" value={view} onChange={setView} tabs={[{ id: "account", label: "By account" }, { id: "lease", label: "By lease" }]} />
      <Card pad={false}>
        <div className="ll-table-wrap">
          <table className="ll-table">
            <thead><tr><th>{view === "account" ? "Account" : "Lease"}</th><th className="num">Lines</th><th className="num">Debit</th><th className="num">Credit</th></tr></thead>
            <tbody>{grouped.map((g) => <tr key={g.key}><td>{g.label}</td><td className="num">{g.n}</td><td className="num"><Money value={g.dr.toFixed(2)} dash /></td><td className="num"><Money value={g.cr.toFixed(2)} dash /></td></tr>)}</tbody>
            <tfoot><tr><td>Total</td><td className="num">{b.lines.length}</td><td className="num"><Money value={t.dr} /></td><td className="num"><Money value={t.cr} /></td></tr></tfoot>
          </table>
        </div>
      </Card>
    </>
  );
}
